//! Scan code set 2's base and `E0` tables, per the IBM PS/2 specification; a code with no name here is no error.

use crate::key::Key;

/// The key a bare set 2 make code names; F7 is `0x83`, so the table spans the byte and breaks need `F0`.
pub(crate) fn key_for(code: u8) -> Option<Key> {
    Some(match code {
        0x01 => Key::F9,
        0x03 => Key::F5,
        0x04 => Key::F3,
        0x05 => Key::F1,
        0x06 => Key::F2,
        0x07 => Key::F12,
        0x09 => Key::F10,
        0x0A => Key::F8,
        0x0B => Key::F6,
        0x0C => Key::F4,
        0x0D => Key::Tab,
        0x0E => Key::Grave,
        0x11 => Key::AltLeft,
        0x12 => Key::ShiftLeft,
        0x14 => Key::CtrlLeft,
        0x15 => Key::Q,
        0x16 => Key::Digit1,
        0x1A => Key::Z,
        0x1B => Key::S,
        0x1C => Key::A,
        0x1D => Key::W,
        0x1E => Key::Digit2,
        0x21 => Key::C,
        0x22 => Key::X,
        0x23 => Key::D,
        0x24 => Key::E,
        0x25 => Key::Digit4,
        0x26 => Key::Digit3,
        0x29 => Key::Space,
        0x2A => Key::V,
        0x2B => Key::F,
        0x2C => Key::T,
        0x2D => Key::R,
        0x2E => Key::Digit5,
        0x31 => Key::N,
        0x32 => Key::B,
        0x33 => Key::H,
        0x34 => Key::G,
        0x35 => Key::Y,
        0x36 => Key::Digit6,
        0x3A => Key::M,
        0x3B => Key::J,
        0x3C => Key::U,
        0x3D => Key::Digit7,
        0x3E => Key::Digit8,
        0x41 => Key::Comma,
        0x42 => Key::K,
        0x43 => Key::I,
        0x44 => Key::O,
        0x45 => Key::Digit0,
        0x46 => Key::Digit9,
        0x49 => Key::Period,
        0x4A => Key::Slash,
        0x4B => Key::L,
        0x4C => Key::Semicolon,
        0x4D => Key::P,
        0x4E => Key::Minus,
        0x52 => Key::Apostrophe,
        0x54 => Key::LeftBracket,
        0x55 => Key::Equal,
        0x58 => Key::CapsLock,
        0x59 => Key::ShiftRight,
        0x5A => Key::Enter,
        0x5B => Key::RightBracket,
        0x5D => Key::Backslash,
        0x66 => Key::Backspace,
        0x69 => Key::Keypad1,
        0x6B => Key::Keypad4,
        0x6C => Key::Keypad7,
        0x70 => Key::Keypad0,
        0x71 => Key::KeypadPeriod,
        0x72 => Key::Keypad2,
        0x73 => Key::Keypad5,
        0x74 => Key::Keypad6,
        0x75 => Key::Keypad8,
        0x76 => Key::Escape,
        0x77 => Key::NumLock,
        0x78 => Key::F11,
        0x79 => Key::KeypadPlus,
        0x7A => Key::Keypad3,
        0x7B => Key::KeypadMinus,
        0x7C => Key::KeypadMultiply,
        0x7D => Key::Keypad9,
        0x7E => Key::ScrollLock,
        0x83 => Key::F7,
        _ => return None,
    })
}

/// The key an `E0`-prefixed code names: navigation, the right modifiers and two keypad keys.
pub(crate) fn extended_key_for(code: u8) -> Option<Key> {
    Some(match code {
        0x11 => Key::AltRight,
        0x14 => Key::CtrlRight,
        0x1F => Key::SuperLeft,
        0x27 => Key::SuperRight,
        0x2F => Key::Menu,
        0x4A => Key::KeypadDivide,
        0x5A => Key::KeypadEnter,
        0x69 => Key::End,
        0x6B => Key::ArrowLeft,
        0x6C => Key::Home,
        0x70 => Key::Insert,
        0x71 => Key::Delete,
        0x72 => Key::ArrowDown,
        0x74 => Key::ArrowRight,
        0x75 => Key::ArrowUp,
        0x7A => Key::PageDown,
        0x7C => Key::PrintScreen,
        0x7D => Key::PageUp,
        _ => return None,
    })
}

